#!/usr/bin/env python3
"""V19 Nov 2026: replay all 89 October-qualified portfolios, filter profit > 0 & orders > 2.

Reuses immutable Exness November M5 OHLC generated by verified prior 22-replay,
reconstructs the same historical indicator warmup and exact 4-leg executions.
Exits must be observed; open signals count toward order totals but have no PnL.
Does not open real trades. Units are bp of fixed, equally allocated notional.
"""
import argparse
import json
from pathlib import Path

import pandas as pd
import v19_nov2026_22_replay as replay

DEFAULT_CUTOFF = "2026-11-12T18:00:00Z"


def run(args):
    cutoff = pd.Timestamp(args.until).tz_convert("UTC")
    if cutoff != pd.Timestamp(DEFAULT_CUTOFF):
        raise ValueError("Stored November M5 assets were verified only for the locked cutoff: " + DEFAULT_CUTOFF)
    selection = json.loads(args.selected.read_text(encoding="utf-8"))
    candidates = selection["retained"]
    assert selection["base_candidates"] == 89 and len(candidates) == 89
    assert len({x["portfolio"] for x in candidates}) == 89
    assert all(len(x["legs"]) == 4 for x in candidates)

    nov_m5 = {}
    for sym in replay.NAMES:
        src = args.novdir / f"{sym}_2026-11_M5_UTC.csv.gz"
        if not src.exists():
            raise FileNotFoundError(f"Exness verified November M5 data missing: {src}")
        m5 = pd.read_csv(src, parse_dates=["timestamp_utc"], index_col="timestamp_utc")
        m5.index = pd.to_datetime(m5.index, utc=True)
        assert not m5.empty and m5.index.is_monotonic_increasing
        assert m5.index.min() >= replay.START and m5.index.max() < cutoff
        assert "tick_count" in m5 and (m5.tick_count > 0).all()
        nov_m5[sym] = m5
        print("V19_89_NOV_M5", sym, len(m5), m5.index.min(), m5.index.max(), flush=True)
    frames = {s: replay.rebuild_frames(args.history, s, nov_m5[s]) for s in replay.NAMES}

    leg_names = sorted(set(leg for row in candidates for leg in row["legs"]))
    leg_cache = {}
    for leg in leg_names:
        sym, tf, *_ = leg.split("|")
        if sym not in frames:
            raise ValueError("Symbol without verified November data: "+sym)
        leg_cache[leg] = replay.replay_one_leg(frames[sym][tf], leg, cutoff)
        print("V19_89_NOV_LEG",leg,len(leg_cache[leg]),flush=True)

    rows = []
    for item in candidates:
        records = [e for leg in item["legs"] for e in leg_cache[leg]]
        closed = [e for e in records if e["status"] == "closed"]
        open_ = [e for e in records if e["status"] == "open"]
        pnl_bp = round(float(sum(e["pnl_bp"] for e in closed) / 4), 5)
        n_orders = len(records)
        row = {
            "portfolio": item["portfolio"], "family": item["family"],
            "november_realized_profit_bp": pnl_bp,
            "november_total_entry_orders": n_orders,
            "november_closed_orders": len(closed),
            "november_open_orders": len(open_),
            "november_winning_closed_orders": sum(e["pnl_bp"] > 0 for e in closed),
            "november_losing_closed_orders": sum(e["pnl_bp"] < 0 for e in closed),
            "positive_months_historical": item["positive_months"],
            "profit_2025_jan_to_oct2026_bp": round(float(item["profit_2025_bp"]+item["profit_2026_bp"]),5),
            "october_2026_bp":item["october_2026_bp"],
            "legs": item["legs"],
            "passes_positive_november": pnl_bp > 0,
            "passes_at_least_3_orders": n_orders >= 3,
        }
        row["retained"] = row["passes_positive_november"] and row["passes_at_least_3_orders"]
        rows.append(row)
    rows.sort(key=lambda x: (-x["november_realized_profit_bp"],-x["november_total_entry_orders"],x["portfolio"]))

    # Check exact reproducibility against the independently committed 22-subset replay.
    earlier = json.loads((args.novdir / "V19_nov2026_22_replay.json").read_text(encoding="utf-8"))
    old_lookup = {x["id"]:x for x in earlier["rows"]}
    by_id = {x["portfolio"]:x for x in rows}
    for sid, r in old_lookup.items():
        v = by_id[sid]
        if v["november_realized_profit_bp"] != r["november_realized_profit_bp"] or v["november_total_entry_orders"] != r["november_total_order_signals"]:
            raise AssertionError(f"Replay disagreement vs previously checked 22: {sid} {v} != {r}")
    assert len(old_lookup) == 22

    retained = [x for x in rows if x["retained"]]
    removed = [x for x in rows if not x["retained"]]
    losses = sum(x["november_realized_profit_bp"] < 0 for x in rows)
    zeros = sum(x["november_realized_profit_bp"] == 0 for x in rows)
    profits = sum(x["november_realized_profit_bp"] > 0 for x in rows)
    low_orders = sum(x["november_total_entry_orders"] <= 2 for x in rows)
    nonpositive = losses + zeros
    overlapping = sum(x["november_realized_profit_bp"] <= 0 and x["november_total_entry_orders"] <= 2 for x in rows)
    output = {
        "project": "V19",
        "study": "Nov 2026 out-of-sample replay of all 89 unchanged Oct-positive portfolio specifications",
        "input_candidates": str(args.selected),
        "exness_november_candles": [str(args.novdir / f"{sym}_2026-11_M5_UTC.csv.gz") for sym in replay.NAMES],
        "source_provenance": str(args.novdir / "V19_nov2026_22_replay.json"),
        "period_start_inclusive_utc":replay.START.isoformat(),
        "period_cutoff_exclusive_utc":cutoff.isoformat(),
        "price_assumptions":"Bid/Ask observed at M5 OHLC resampled to each strategy timeframe, 1bp slippage per side. Fixed holding-time exits; no stop loss, swaps, commissions, margin, leverage, or live fills.",
        "pnl_unit":"bp of equal fixed notional; four independent legs equally weighted 1/4. Not USD.",
        "order_count_definition":"Each independent leg entry is an order, including not-yet-closed entries. No fill/rejection simulation.",
        "criteria":"Keep strictly positive realized Nov profit AND at least 3 November entry orders (remove profit <= 0 OR orders <= 2).",
        "counts":{
            "original":len(rows),
            "profitable_november": profits,
            "losing_november": losses,
            "break_even_november": zeros,
            "orders_le_2":low_orders,
            "both_nonpositive_profit_and_orders_le_2": overlapping,
            "removed_nonpositive_profit":nonpositive,
            "removed_only_due_to_low_orders":low_orders-overlapping,
            "removed_union":len(removed),
            "retained":len(retained),
            "unique_legs_replayed":len(leg_cache),
            "verified_22_subportfolio_reproduced":len(old_lookup)
        },
        "retained":retained,
        "removed":removed,
        "all_89":rows,
    }
    assert len(retained)+len(removed)==89
    assert len(removed)==nonpositive+low_orders-overlapping

    out = args.novdir
    (out/"V19_89_nov2026_profit_and_orders_filter.json").write_text(json.dumps(output,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    pd.DataFrame([{k:v for k,v in x.items() if k!="legs"} for x in rows]).to_csv(
        out/"V19_89_nov2026_profit_and_orders_filter.csv",index=False)
    print("V19_89_NOV_FINAL",json.dumps(output["counts"]),flush=True)
    print("V19_89_NOV_RETAINED",json.dumps([{"id":x["portfolio"],"bp":x["november_realized_profit_bp"],"orders":x["november_total_entry_orders"]} for x in retained]),flush=True)
    return output


if __name__ == "__main__":
    p=argparse.ArgumentParser()
    p.add_argument("--history",type=Path,default=Path("data/v19_energies"))
    p.add_argument("--selected",type=Path,default=Path("data/v19_strategy_screen/V19_89_filtered_oct2026.json"))
    p.add_argument("--novdir",type=Path,default=Path("results/v19_november_2026"))
    p.add_argument("--until",default=DEFAULT_CUTOFF)
    run(p.parse_args())
